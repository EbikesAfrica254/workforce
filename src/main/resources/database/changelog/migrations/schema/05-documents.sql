COMMENT ON COLUMN workforce.documents.created_at            IS 'Record creation timestamp in UTC - immutable';
COMMENT ON COLUMN workforce.documents.created_by            IS 'Keycloak user ID of the actor who initiated the upload - immutable';
COMMENT ON COLUMN workforce.documents.document_type         IS 'Type of compliance document uploaded during agent onboarding';
