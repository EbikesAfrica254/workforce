-- comment: create the agents table as the core aggregate for the workforce management context
CREATE TABLE workforce.agents (
  id                          UUID            NOT NULL DEFAULT gen_random_uuid(),
  availability_status         VARCHAR(20)     NOT NULL DEFAULT 'OFFLINE',
  capability_class            VARCHAR(25)     NOT NULL,
  completed_delivery_count    INTEGER         NOT NULL DEFAULT 0,
  created_at                  TIMESTAMPTZ     NOT NULL,
  created_by                  VARCHAR(36)     NOT NULL,
  current_h3_index            VARCHAR(20),
  current_latitude            NUMERIC(10,8),
  current_longitude           NUMERIC(11,8),
  current_orders              INTEGER NOT NULL DEFAULT 0 CHECK (current_orders >= 0),
  email                       VARCHAR(255),
  first_name                  VARCHAR(100)    NOT NULL,
  last_location_updated_at    TIMESTAMPTZ,
  last_name                   VARCHAR(100)    NOT NULL,
  location_source             VARCHAR(20),
  max_concurrent_orders       SMALLINT        NOT NULL,
  national_id_number          VARCHAR(20)     NOT NULL,
  national_id_type            VARCHAR(20)     NOT NULL DEFAULT 'NATIONAL_ID',
  on_time_delivery_count      INTEGER         NOT NULL DEFAULT 0 CHECK (on_time_delivery_count >= 0),
  phone_number                VARCHAR(20)     NOT NULL,
  alternate_phone_number      VARCHAR(20),
  rejection_reason            VARCHAR(1000),
  reliability_score           NUMERIC(5,2),
  updated_at                  TIMESTAMPTZ,
  updated_by                  VARCHAR(36),
  user_id                     VARCHAR(36)     NOT NULL,
  version                     BIGINT          NOT NULL DEFAULT 0,

  CONSTRAINT pk_agents
      PRIMARY KEY (id)
);

