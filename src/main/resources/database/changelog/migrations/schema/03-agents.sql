    ADD CONSTRAINT chk_agents_national_id_type
        CHECK (national_id_type IN ('NATIONAL_ID', 'PASSPORT'));

ALTER TABLE workforce.agents
    ADD CONSTRAINT chk_agents_phone_number
        CHECK (phone_number ~ '^\+[1-9]\d{1,14}$');

ALTER TABLE workforce.agents
    ADD CONSTRAINT chk_agents_alternate_phone_number
        CHECK (alternate_phone_number IS NULL OR alternate_phone_number ~ '^\+[1-9]\d{1,14}$');

ALTER TABLE workforce.agents
    ADD CONSTRAINT chk_agents_reliability_score
        CHECK (reliability_score IS NULL OR (reliability_score >= 0 AND reliability_score <= 100));

ALTER TABLE workforce.agents
    ADD CONSTRAINT chk_agents_location_fields_consistent
        CHECK (
            (current_latitude IS NULL AND current_longitude IS NULL AND current_h3_index IS NULL)
                OR
            (current_latitude IS NOT NULL AND current_longitude IS NOT NULL AND current_h3_index IS NOT NULL)
            );

